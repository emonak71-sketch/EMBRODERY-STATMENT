const CACHE_NAME = 'embroidery-statement-shell-v1';
const APP_CACHE_PREFIX = 'embroidery-statement-';
const APP_SHELL = ['/', '/index.css', '/manifest.json', '/embroidery-statement-logo.jpg'];

self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(CACHE_NAME)
      .then(cache => cache.addAll(APP_SHELL))
      .catch(() => undefined)
  );
  self.skipWaiting();
});

self.addEventListener('activate', event => {
  event.waitUntil(
    caches.keys().then(names =>
      Promise.all(names
        .filter(name => name.startsWith(APP_CACHE_PREFIX) && name !== CACHE_NAME)
        .map(name => caches.delete(name))
      )
    ).then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith(
    fetch(request).then(response => {
      if (response.ok && response.type === 'basic') {
        const copy = response.clone();
        event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.put(request, copy)));
      }
      return response;
    }).catch(async () => {
      const cached = await caches.match(request);
      if (cached) return cached;
      const appShell = await caches.match('/');
      return appShell || Response.error();
    })
  );
});
