import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('./subscriptionStatus.ts',import.meta.url),'utf8');
const {outputText}=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}});
const module={exports:{}};
new Function('module','exports',outputText)(module,module.exports);
const {accountPlan}=module.exports;
const now=Date.parse('2026-11-06T12:00:00Z');
const day=86_400_000;
const date=days=>new Date(now+days*day).toISOString();
const trial={has_access:true,access_source:'free_trial',access_until:date(14),trial_ends_at:date(14),manual_access_starts_at:null,manual_access_until:null,subscription_access_until:null};
assert.equal(accountPlan(trial,now).tier,'trial');
assert.equal(accountPlan(trial,now).days,14);
const scheduled=accountPlan({...trial,manual_access_starts_at:date(14),manual_access_until:date(44)},now);
assert.equal(scheduled.tier,'pro');
assert.equal(scheduled.scheduled,true);
assert.equal(scheduled.days,44,'Countdown must include remaining trial before the purchased period ends');
const active=accountPlan({...trial,access_source:'owner_grant',access_until:date(0.25),trial_ends_at:date(-10),manual_access_starts_at:date(-10),manual_access_until:date(0.25)},now);
assert.equal(active.days,1,'Partial days must not display as expired');
assert.equal(active.scheduled,false);
assert.equal(accountPlan({...trial,access_source:'expired',has_access:false,trial_ends_at:date(-1),access_until:null},now).days,0);
assert.equal(accountPlan({...trial,access_source:'subscription',subscription_access_until:date(30)},now).days,30);
assert.equal(accountPlan({...trial,access_source:'owner_admin'},now).tier,'owner');
assert.equal(accountPlan(null,now),null);
assert.ok(Number.isFinite(accountPlan({...trial,trial_ends_at:'invalid'},now).days));
console.log('PASS: trial, scheduled Pro, active Pro, partial-day, expired, owner and invalid-date countdowns.');
